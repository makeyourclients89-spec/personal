import os
import shutil
import re

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
KOTLIN_DIR = os.path.join(
    BASE_DIR, "android", "app", "src", "main", "kotlin", "com", "example", "call_detection_flutter"
)
MANIFEST_PATH = os.path.join(
    BASE_DIR, "android", "app", "src", "main", "AndroidManifest.xml"
)
APP_BUILD_GRADLE = os.path.join(BASE_DIR, "android", "app", "build.gradle")
APP_BUILD_GRADLE_KTS = os.path.join(BASE_DIR, "android", "app", "build.gradle.kts")

print("--> Setting up Android native files for AI Call Detection & Assistant...")

# 1. Kotlin Directory Setup & File Copying
os.makedirs(KOTLIN_DIR, exist_ok=True)

files_to_copy = ["MainActivity.kt", "CallScreeningServiceImpl.kt", "CallReceiver.kt"]
for fname in files_to_copy:
    src = os.path.join(BASE_DIR, "android_changes", fname)
    if os.path.exists(src):
        dst = os.path.join(KOTLIN_DIR, fname)
        shutil.copy2(src, dst)
        print(f"[OK] Copied {fname}")
    else:
        print(f"[Notice] {src} not found.")

# 2. AndroidManifest.xml configuration
if os.path.exists(MANIFEST_PATH):
    with open(MANIFEST_PATH, "r", encoding="utf-8") as f:
        content = f.read()

    # Permissions list
    permissions = [
        "android.permission.READ_PHONE_STATE",
        "android.permission.READ_CALL_LOG",
        "android.permission.RECORD_AUDIO",
        "android.permission.POST_NOTIFICATIONS",
        "android.permission.VIBRATE",
        "android.permission.MODIFY_AUDIO_SETTINGS"
    ]

    perm_block = "\n"
    for p in permissions:
        if p not in content:
            perm_block += f'    <uses-permission android:name="{p}" />\n'

    if perm_block.strip():
        if "<application" in content:
            content = content.replace("<application", perm_block + "    <application", 1)
            print("[OK] Added runtime and telephony permissions to AndroidManifest")

    # Receiver and Service block
    receiver_tag = '''
        <receiver
            android:name=".CallReceiver"
            android:exported="true">
            <intent-filter>
                <action android:name="android.intent.action.PHONE_STATE" />
            </intent-filter>
        </receiver>
'''
    service_tag = '''
        <service
            android:name=".CallScreeningServiceImpl"
            android:label="AI Call Assistant Screening"
            android:permission="android.permission.BIND_SCREENING_SERVICE"
            android:exported="true">
            <intent-filter>
                <action android:name="android.telecom.CallScreeningService" />
            </intent-filter>
        </service>
'''

    components_to_add = ""
    if "CallReceiver" not in content:
        components_to_add += receiver_tag
    if "CallScreeningServiceImpl" not in content:
        components_to_add += service_tag

    if components_to_add and "</application>" in content:
        content = content.replace("</application>", components_to_add + "    </application>", 1)
        print("[OK] Added CallReceiver and CallScreeningServiceImpl to AndroidManifest")

    with open(MANIFEST_PATH, "w", encoding="utf-8") as f:
        f.write(content)
    print("[OK] AndroidManifest.xml updated successfully")
else:
    print(f"[Notice] {MANIFEST_PATH} not found yet (will be generated by flutter create).")

# 3. Ensure minSdk >= 24 in build gradle
gradle_file = APP_BUILD_GRADLE if os.path.exists(APP_BUILD_GRADLE) else (APP_BUILD_GRADLE_KTS if os.path.exists(APP_BUILD_GRADLE_KTS) else None)
if gradle_file:
    with open(gradle_file, "r", encoding="utf-8") as f:
        g_content = f.read()

    new_g = re.sub(r'minSdkVersion\s+(flutter\.minSdkVersion|\d+)', 'minSdkVersion 24', g_content)
    new_g = re.sub(r'minSdk\s*=\s*(flutter\.minSdkVersion|\d+)', 'minSdk = 24', new_g)
    if new_g != g_content:
        with open(gradle_file, "w", encoding="utf-8") as f:
            f.write(new_g)
        print("[OK] minSdk updated to 24 in build gradle")

print("--> Setup complete.")
